"""Keep both presentations synchronized with the single requirements register.

Called by latexmk before either build. No science data or models are changed.
Narrative paragraphs preserve every requirement and evidence field, without
IDs, status columns, repeated captions or verification-method columns.
"""
import json
from pathlib import Path
try:
    from .render_section3_requirements import ROOT, REG, GROUPS, ASSESS, evidence, tex, render, write_if_changed
except ImportError:  # direct CLI invocation
    from render_section3_requirements import ROOT, REG, GROUPS, ASSESS, evidence, tex, render, write_if_changed


def narrative_requirement(s):
    # Modal change is editorial: obligations remain obligations, not achieved facts.
    return s.replace(' shall ', ' must ').replace('OPEN DERIVED REQUIREMENTS', 'open allocations').replace('OPEN DERIVED REQUIREMENT', 'open allocation')


def render_narrative():
    rows = json.loads(REG.read_text())['requirements']
    target = ROOT / 'sections/narrative'
    target.mkdir(exist_ok=True)
    for slug, subs, title in GROUPS:
        selected = [r for r in rows if r['subsystem'] in subs]
        text = '% Generated by scripts/render_mcr_editions.py; edit the shared register.\n'
        text += r'\paragraph{Operating constraints and evidence.} ' + '\n'
        for i, r in enumerate(selected):
            text += '% Shared source: ' + r['id'] + '\n'
            text += tex(narrative_requirement(r['requirement'])) + ' ' + tex(evidence(r)) + '\n'
            if i % 2 == 1 or i == len(selected)-1:
                text += '\n'
        assessment = ASSESS[slug]
        assessment = assessment.replace('The tier rows flow down Section 1 without replacing its criteria:', 'Section 1 remains authoritative:')
        assessment = assessment.replace('Requirements marked S support only their stated reference/model scope; Corrected', 'Software and model evidence supports only its stated scope. Corrected')
        text += r'\paragraph{Feasibility assessment.} ' + tex(assessment) + '\n'
        path = target / f'{slug}.tex'
        write_if_changed(path, text)


if __name__ == '__main__':
    # Existing renderer preserves the exact full-edition wording and traceability.
    render()
    render_narrative()
